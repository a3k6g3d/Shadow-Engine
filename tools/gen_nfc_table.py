"""Writes crates/shadow-model/src/nfc_table.rs and eval/fixtures/nfc.txt.

The checkpoint's tokenizer.json normalizes every text to NFC before it is tokenized (the GGUF does not say so), and
Rust's standard library has no Unicode normalization.  So Shadow carries the three tables NFC is built from, generated
once from Python's unicodedata (the Unicode version is written into the file):

  DECOMP   canonical decompositions: (code point, first, second) with second = 0 for a singleton
  COMPOSE  the primary composites: (first, second, composite), the pairs that recompose under NFC (composition
           exclusions and singletons left out, found by asking unicodedata rather than by listing them)
  CCC      canonical combining classes, as ranges

Hangul is algorithmic and lives in code.  The fixture is 4,000 random strings over the code points where NFC does
something (combining marks, Latin and Greek letters with accents, Hangul jamo and syllables, singletons, Indic and
Tibetan composites, compatibility forms that must NOT change), with Python's NFC of each; the Rust implementation must
match all of them.

    python tools/gen_nfc_table.py
"""
import pathlib
import random
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "shadow-model" / "src" / "nfc_table.rs"
FIX = ROOT / "eval" / "fixtures" / "nfc.txt"


def main() -> None:
    decomp, compose = [], []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        assert len(parts) in (1, 2), hex(cp)
        decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    compose.sort()
    ccc = []
    for cp in range(sys.maxunicode + 1):
        c = unicodedata.combining(chr(cp))
        if not c:
            continue
        if ccc and ccc[-1][1] == cp - 1 and ccc[-1][2] == c:
            ccc[-1][1] = cp
        else:
            ccc.append([cp, cp, c])

    def rows(name, ty, items, fmt):
        out = [f"pub const {name}: &[{ty}] = &["]
        line = []
        for it in items:
            line.append(fmt(it))
            if len(line) == 5:
                out.append("    " + ", ".join(line) + ",")
                line = []
        if line:
            out.append("    " + ", ".join(line) + ",")
        out.append("];")
        return out

    lines = [
        "// Generated by tools/gen_nfc_table.py - do not edit.",
        f"// Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]}): the tables NFC is built from.",
        "#![cfg_attr(rustfmt, rustfmt::skip)]",
        "",
        f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";",
        "",
        "/// (code point, first, second); second = 0 for a singleton.  Sorted by code point.",
    ]
    lines += rows("DECOMP", "(u32, u32, u32)", decomp, lambda t: f"(0x{t[0]:X}, 0x{t[1]:X}, 0x{t[2]:X})")
    lines += ["", "/// (first, second, composite).  Sorted by (first, second)."]
    lines += rows("COMPOSE", "(u32, u32, u32)", compose, lambda t: f"(0x{t[0]:X}, 0x{t[1]:X}, 0x{t[2]:X})")
    lines += ["", "/// (first, last, canonical combining class).  Sorted."]
    lines += rows("CCC", "(u32, u32, u8)", ccc, lambda t: f"(0x{t[0]:X}, 0x{t[1]:X}, {t[2]})")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # the fixture: random strings over the interesting code points
    pool = (list(range(0x300, 0x370)) + list(range(0x41, 0x7B)) + list(range(0xC0, 0x180)) + list(range(0x370, 0x400))
            + list(range(0x410, 0x450)) + list(range(0x1100, 0x1113)) + list(range(0x1161, 0x1176))
            + list(range(0x11A8, 0x11C3)) + list(range(0xAC00, 0xAC00 + 600, 7)) + [0x212A, 0x212B, 0x2126, 0x1E9B, 0x0344]
            + list(range(0x1E00, 0x1F00, 3)) + list(range(0x0958, 0x0960)) + list(range(0x093C, 0x094D))
            + list(range(0xF71, 0xF80)) + list(range(0x3099, 0x309B)) + list(range(0x3040, 0x30A0, 5))
            + list(range(0xFB00, 0xFB10)) + list(range(0x2460, 0x2470)) + [0x20, 0x0A, 0x1D15E, 0x1D1BB, 0x1D165, 0x1D16D])
    pool = [c for c in pool if not 0xD800 <= c <= 0xDFFF]
    rng = random.Random(20261026)
    fx = ["# Generated by tools/gen_nfc_table.py.  Each line: input code points (hex), a colon, NFC code points (hex)."]
    for _ in range(4000):
        s = "".join(chr(rng.choice(pool)) for _ in range(rng.randint(1, 8)))
        n = unicodedata.normalize("NFC", s)
        fx.append(" ".join(f"{ord(c):X}" for c in s) + ":" + " ".join(f"{ord(c):X}" for c in n))
    FIX.parent.mkdir(parents=True, exist_ok=True)
    FIX.write_text("\n".join(fx) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(decomp)} decompositions, {len(compose)} compositions, {len(ccc)} ccc ranges; "
          f"{len(fx) - 1} fixture strings; Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main()
