"""Writes crates/shadow-model/src/quant_tables.rs and kernels/iq_tables.cuh: the lookup tables the IQ quant formats are defined by - the
iq2s / iq3xxs / iq3s grids, the 128 sign patterns (ksigns) and IQ4_NL's 16 values.

They are data, not something to re-derive: they come from ggml (MIT, ggml.ai), read here through the `gguf` Python
package that ships them (pip install gguf).  The package version is written into the file.

    python tools/gen_quant_tables.py
"""
import importlib.metadata
import pathlib

import numpy as np
from gguf import quants

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "shadow-model" / "src" / "quant_tables.rs"
CUH = ROOT / "kernels" / "iq_tables.cuh"


def grid(cls) -> np.ndarray:
    cls.init_grid()
    g = cls.grid.reshape(cls.grid_shape)
    assert np.all(g == np.round(g)) and g.min() >= 0 and g.max() < 256, cls.__name__
    return g.astype(np.uint8)


def table(name: str, g: np.ndarray) -> list[str]:
    rows, width = g.shape
    out = [f"pub const {name}: [[u8; {width}]; {rows}] = ["]
    for r in g:
        out.append("    [" + ", ".join(f"0x{v:02x}" for v in r) + "],")
    out.append("];")
    return out


def main() -> None:
    ver = importlib.metadata.version("gguf")
    lines = [
        "// Generated by tools/gen_quant_tables.py - do not edit.",
        f"// The IQ lookup tables from ggml (MIT, ggml.ai), read through the gguf Python package {ver}.",
        "#![cfg_attr(rustfmt, rustfmt::skip)]",
        "",
        f"pub const GGUF_PY_VERSION: &str = \"{ver}\";",
        "",
    ]
    lines += table("IQ2S_GRID", grid(quants.IQ2_S)) + [""]
    lines += table("IQ2XXS_GRID", grid(quants.IQ2_XXS)) + [""]
    lines += table("IQ2XS_GRID", grid(quants.IQ2_XS)) + [""]
    lines += table("IQ3XXS_GRID", grid(quants.IQ3_XXS)) + [""]
    lines += table("IQ3S_GRID", grid(quants.IQ3_S)) + [""]
    ks = np.frombuffer(quants.IQ2_XXS.ksigns, dtype=np.uint8)
    assert ks.shape == (128,)
    lines.append("pub const KSIGNS: [u8; 128] = [" + ", ".join(f"0x{v:02x}" for v in ks) + "];")
    lines.append("")
    lines.append("pub const IQ4NL_VALUES: [i8; 16] = [" + ", ".join(str(v) for v in quants.IQ4_NL.kvalues) + "];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # The same tables for the GPU, in global memory, 8-byte aligned, read through the L1 cache (11 KiB in all; __constant__ memory serializes a warp whose lanes read different rows, which every IQ decoder does).
    cu = [
        "// Generated by tools/gen_quant_tables.py - do not edit.",
        f"// The IQ lookup tables from ggml (MIT, ggml.ai), read through the gguf Python package {ver}; the same data",
        "// as crates/shadow-model/src/quant_tables.rs.  Listed as a header of the kernel files that need it.",
        "",
    ]
    for name, cls in (("kIQ2SGrid", quants.IQ2_S), ("kIQ2XXSGrid", quants.IQ2_XXS), ("kIQ2XSGrid", quants.IQ2_XS),
                      ("kIQ3XXSGrid", quants.IQ3_XXS), ("kIQ3SGrid", quants.IQ3_S)):
        g = grid(cls)
        rows, width = g.shape
        cu.append(f"__device__ const u8 __align__(8) {name}[{rows}][{width}] = {{")
        for r in g:
            cu.append("    {" + ", ".join(f"0x{v:02x}" for v in r) + "},")
        cu.append("};")
        cu.append("")
    cu.append("__device__ const u8 __align__(8) kKSigns[128] = {" + ", ".join(f"0x{v:02x}" for v in ks) + "};")
    CUH.write_text("\n".join(cu) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}, {CUH}: gguf {ver}")


if __name__ == "__main__":
    main()
