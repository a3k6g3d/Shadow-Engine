"""Writes crates/shadow-model/src/unicode_table.rs: the code point ranges in the general categories used by the
qwen35 pre-tokenizer:
  LU_LT = 1   (\\p{Lu}, \\p{Lt})
  LL    = 2   (\\p{Ll})
  LM_LO = 4   (\\p{Lm}, \\p{Lo})   -> L = 1 | 2 | 4 = 7
  M     = 8   (\\p{M})
  N     = 16  (\\p{N})
  P_S   = 32  (\\p{P}, \\p{S})

Rust's standard library has no general-category lookup (`char::is_alphabetic` is the Alphabetic property, which is not
\\p{L}), so the table is generated once from Python's unicodedata and committed.  The Unicode version is written into
the file; regenerate with a newer Python to move it.

    python tools/gen_unicode_table.py
"""
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "shadow-model" / "src" / "unicode_table.rs"


def flag_for(cat: str) -> int:
    if cat in ("Lu", "Lt"):
        return 1
    if cat == "Ll":
        return 2
    if cat in ("Lm", "Lo"):
        return 4
    if cat[0] == "M":
        return 8
    if cat[0] == "N":
        return 16
    if cat[0] in ("P", "S"):
        return 32
    return 0


def main() -> None:
    ranges = []
    for cp in range(sys.maxunicode + 1):
        f = flag_for(unicodedata.category(chr(cp)))
        if not f:
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == f:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, f])
    lines = [
        "// Generated by tools/gen_unicode_table.py - do not edit.",
        f"// Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]}): "
        "Lu|Lt=1, Ll=2, Lm|Lo=4 (L=7), M=8, N=16, P|S=32.",
        "",
        f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";",
        "",
        "/// (first, last, flags), sorted, non-overlapping.",
        "#[rustfmt::skip]",
        "pub const RANGES: &[(u32, u32, u8)] = &[",
    ]
    row = []
    for a, b, f in ranges:
        row.append(f"(0x{a:X}, 0x{b:X}, {f})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(ranges)} ranges, Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main()
