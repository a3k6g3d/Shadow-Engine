"""Writes eval/fixtures/dequant.txt: real blocks of the model, one or more per quant type, with what the gguf Python
package (ggml's own reference dequantizer, MIT) makes of them.  crates/shadow-model/tests/dequant.rs checks Shadow's
Rust dequantizer against it, bit for bit.

Tensor offsets come from Shadow's own reader (`shadow inspect --tensors`): gguf's GGUFReader refuses the whole
file over the one type it does not know (Q2_0).  Only the chosen blocks are read, by seek.

    cargo build --release -p shadow-model
    python tools/gen_dequant_fixtures.py MODEL-00001-of-0000N.gguf
"""
import pathlib
import re
import subprocess
import sys

import numpy as np
from gguf import quants
from gguf.constants import GGML_QUANT_SIZES, GGMLQuantizationType

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADOW = ROOT / "target" / "release" / "shadow.exe"

OUT = ROOT / "eval" / "fixtures" / "dequant.txt"
WANT = ["F32", "F16", "BF16", "Q4_K", "Q5_K", "Q6_K", "IQ2_S", "IQ3_XXS", "IQ3_S", "IQ4_NL", "IQ4_XS"]
PER_TENSOR = 4      # blocks: first, two in the middle, last
TENSORS_PER_TYPE = 2


ROW = re.compile(r"^\s+(\S+)\s+(\S+)\s+\[[^\]]*\]\s+shard (\d+) @\s+(\d+)\s+(\d+) bytes$")


def tensors(first: pathlib.Path):
    """(name, type, shard path, offset, bytes) for every tensor, from `shadow inspect --tensors`."""
    out = subprocess.run([str(SHADOW), "inspect", str(first), "--tensors"], capture_output=True, text=True, check=True)
    paths = [pathlib.Path(l.split()[0]) for l in out.stdout.splitlines() if l.startswith("  ") and " v3 " in l]
    rows = []
    for line in out.stdout.splitlines():
        m = ROW.match(line)
        if m:
            rows.append((m.group(1), m.group(2), paths[int(m.group(3))], int(m.group(4)), int(m.group(5))))
    return rows


def main() -> None:
    first = pathlib.Path(sys.argv[1])
    picked: dict[str, int] = {}
    lines = ["# Generated by tools/gen_dequant_fixtures.py from the model file; see that script.",
             "# Each record: TYPE TENSOR BLOCK, the block's bytes in hex, the expected f32 values as hex bit patterns."]
    files = {}
    for name, ty, path, offset, nbytes in tensors(first):
        if ty not in WANT or picked.get(ty, 0) >= TENSORS_PER_TYPE:
            continue
        qt = GGMLQuantizationType[ty]
        block, size = GGML_QUANT_SIZES[qt]
        f = files.setdefault(path, open(path, "rb"))
        n_blocks = nbytes // size
        for bi in sorted({0, n_blocks // 3, (2 * n_blocks) // 3, n_blocks - 1}):
            f.seek(offset + bi * size)
            b = np.frombuffer(f.read(size), dtype=np.uint8)
            if ty in ("F32", "F16", "BF16"):
                vals = b.view({"F32": np.float32, "F16": np.float16, "BF16": np.uint16}[ty])
                if ty == "BF16":
                    vals = (vals.astype(np.uint32) << 16).view(np.float32)
                vals = vals.astype(np.float32)
            else:
                vals = quants.dequantize(b, qt).astype(np.float32).reshape(-1)
            assert vals.size == block, (ty, vals.size)
            lines.append(f"{ty} {name} {bi}")
            lines.append(b.tobytes().hex())
            lines.append("".join(f"{v:08x}" for v in vals.view(np.uint32)))
        picked[ty] = picked.get(ty, 0) + 1
    missing = [w for w in WANT if w not in picked]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {sum(picked.values())} tensors, types {sorted(picked)}; not found: {missing}")


if __name__ == "__main__":
    main()
